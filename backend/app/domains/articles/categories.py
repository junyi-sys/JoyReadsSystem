def detect_category(topic: str, content: str = "") -> str:
    """Detect topic category from text. Topic keywords weighted 3x, content 1x."""
    text = topic + content
    scores: dict[str, int] = {}
    for cat, keywords in CATEGORY_KEYWORDS.items():
        topic_score = sum(3 for kw in keywords if kw in topic)
        content_score = sum(1 for kw in keywords if kw in content)
        total = topic_score + content_score
        if total > 0:
            scores[cat] = total

    if not scores:
        return "其他"

    return max(scores, key=scores.get)


